"""Regenerate PORTING_STATUS.md from the reference Python package.

The reference interpreter (the one that has `simplecadapi` + OCP) and the interpreter the C++
module was built for are usually different Pythons, so the exported names travel as JSON:

    .venv/bin/python tools/gen_status.py --dump-cpp-names <build>/python > /tmp/cpp_names.json
    <ref>/.venv/bin/python tools/gen_status.py --cpp-names /tmp/cpp_names.json

(`--cpp <build>/python` imports the module directly and only works when both are the same Python.)

The first table is every public operator of simplecadapi.operators; the "C++" column
is filled by checking which names the C++ module exports.
"""
from __future__ import annotations

import argparse
import inspect
import json
import sys
from pathlib import Path

AREAS = {
    # operator module -> default area
    "geometry": "ops-geometry",
    "features": "ops-features",
    "boolean": "ops-features",
    "transform": "ops-features",
    "selection": "semantic",
    "sketch": "sketch",
    "product": "product",
    "_support": "semantic",
}
SURFACE = ("surface", "bezier", "gordon", "ruled", "patch", "trim_surface", "fill_holes", "sew_faces",
           "free_boundaries", "solid_from_shell", "loft_rshell", "cylindrical_surface", "fit_point_grid")


def area_of(name: str, module: str) -> str:
    if any(token in name for token in SURFACE):
        return "surface"
    return AREAS.get(module, module)


def exported_names(build_python_dir: str) -> set[str]:
    """The public names of the built `simplecadapi._cpp` package."""
    sys.path.insert(0, build_python_dir)
    import importlib

    cpp = importlib.import_module("simplecadapi._cpp")
    return {n for n in dir(cpp) if not n.startswith("_")}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cpp", help="path holding the built simplecadapi._cpp package (same Python as this script)")
    ap.add_argument("--cpp-names", help="JSON list of the names simplecadapi._cpp exports (see --dump-cpp-names)")
    ap.add_argument("--dump-cpp-names", metavar="BUILD_PYTHON_DIR",
                    help="print the exported names of the package in that directory as JSON and exit")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "PORTING_STATUS.md"))
    args = ap.parse_args()

    if args.dump_cpp_names:
        print(json.dumps(sorted(exported_names(args.dump_cpp_names))))
        return 0

    import simplecadapi
    from simplecadapi import operators as ops

    cpp_names: set[str] = set()
    if args.cpp_names:
        cpp_names = set(json.loads(Path(args.cpp_names).read_text()))
    elif args.cpp:
        cpp_names = exported_names(args.cpp)

    rows = []
    for name in sorted(ops.__all__):
        obj = getattr(ops, name, None)
        if not callable(obj) or inspect.isclass(obj):
            continue
        full = getattr(obj, "__module__", "")
        if not full.startswith("simplecadapi.operators") or name.startswith("_"):
            continue
        module = full.rsplit(".", 1)[-1]
        rows.append((name, module, area_of(name, module), "done" if name in cpp_names else "todo"))

    other = []
    for name in sorted(set(dir(simplecadapi)) - {r[0] for r in rows}):
        if name.startswith("_"):
            continue
        obj = getattr(simplecadapi, name)
        other.append((name, "class" if inspect.isclass(obj) else ("function" if callable(obj) else "value")))

    lines = ["# Porting status", "",
             "Generated by `tools/gen_status.py`; do not edit by hand. Status: `done` means the name is exported by "
             "`simplecadapi._cpp`; whether it is *aligned* is decided by the area's parity tests.", "",
             f"Operators: {len(rows)}, done: {sum(1 for r in rows if r[3] == 'done')}", "",
             "| Python operator | Python module | Area | Status |", "|---|---|---|---|"]
    lines += [f"| `{n}` | {m} | {a} | {s} |" for n, m, a, s in rows]
    lines += ["", "## Other public names of `simplecadapi`", "", "| Name | Kind |", "|---|---|"]
    lines += [f"| `{n}` | {k} |" for n, k in other]
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} operators, {len(other)} other names -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
