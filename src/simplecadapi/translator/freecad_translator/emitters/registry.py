def emit_native_node(
    translator: Any,
    node: OperationNode,
    **kwargs: str,
) -> Optional[List[str]]:
    method_name = EMITTER_METHOD_BY_OP.get(node.op)
    if method_name is None:
        return None
    return getattr(translator, method_name)(node, **kwargs)


