"""Kernel strategies behind explicit flags: the Y-transition fillet (``strategy_auto_y_patch``) and the graph patch
(``strategy_graph_patch``).  Both need the SDK's OCCT patch set (src/cpp/patches/occt, fillet-robustness-4); on another
kernel they must refuse with a ValueError, never fall back silently."""

import math

import pytest

import simplecadapi as s
from simplecadapi import _cpp
from simplecadapi._cpp import _kernel_capabilities
from simplecadapi.recording.graph import GraphSession

CAPS = _kernel_capabilities()
needs_y = pytest.mark.skipif(not CAPS["y_patch"], reason="kernel without the Y-transition strategy")
needs_graph = pytest.mark.skipif(not CAPS["graph_patch"], reason="kernel without the graph patch")

R, H = 50.0, 40.0


def plate_post():
    """A post of radius R flush with the side y = -R of a plate 3R x 2R x H (the reference Y junction)."""
    post = s.make_cylinder_rsolid(R, 2 * H)
    plate = s.make_box_rsolid(3 * R, 2 * R, H, bottom_face_center=(1.5 * R, 0, 0))
    return s.union_rsolid(post, plate)


def _at(edge):
    c = edge.get_center()
    return c.x, c.y, c.z


def junction_edges(body):
    """The concave root of the post on the plate top and the convex top edge of the flush side y = -R."""
    circles = s.ql.edges().where(s.ql.prop("geom.type", "==", "CIRCLE")).resolve(body)
    lines = s.ql.edges().where(s.ql.prop("geom.type", "==", "LINE")).resolve(body)
    root = [e for e in circles if abs(_at(e)[2] - H) < 1e-6]  # get_center() is the arc's centroid
    side = [e for e in lines if abs(_at(e)[1] + R) < 1e-6 and abs(_at(e)[2] - H) < 1e-6]
    assert root and len(side) == 1
    return root + side


def test_capabilities_are_reported():
    assert set(CAPS) == {"y_patch", "graph_patch"}
    assert all(isinstance(v, bool) for v in CAPS.values())


@pytest.mark.skipif(CAPS["y_patch"], reason="the refusal is for kernels without the strategy")
def test_without_the_kernel_strategy_the_flag_refuses():
    body = plate_post()
    with pytest.raises(s.SimpleCADError, match="fillet-robustness-4"):
        s.fillet_rsolid(body, junction_edges(body), 5.0, strategy_auto_y_patch=True)


@needs_y
@pytest.mark.parametrize("radius", [2.5, 5.0, 8.0])
def test_y_patch_closes_the_flush_post_junction(radius):
    body = plate_post()
    out = s.fillet_rsolid(body, junction_edges(body), radius, strategy_auto_y_patch=True, generated_faces_tag="round")
    # (fillet_rsolid itself rejects an invalid or volume-inconsistent blend result)
    # bands and the two ribbons are all generated by the selected edges
    rounds = s.ql.faces().where(s.ql.tag("round")).resolve(out)
    assert len(rounds) >= 4
    # the concave band adds material, the convex one removes some; both are small next to the body
    assert abs(out.get_volume() - body.get_volume()) < 0.01 * body.get_volume()


@needs_y
def test_y_patch_off_is_the_standard_algorithm():
    body = plate_post()
    edges = s.ql.edges().where(s.ql.prop("geom.center.z", ">", 2 * H - 1e-6)).resolve(body)
    plain = s.fillet_rsolid(body, edges, 3.0)
    flagged = s.fillet_rsolid(body, edges, 3.0, strategy_auto_y_patch=True)  # no junction among these edges
    assert flagged.get_volume() == pytest.approx(plain.get_volume(), rel=1e-12)
    assert len(s.ql.faces().resolve(flagged)) == len(s.ql.faces().resolve(plain))


@needs_y
@pytest.mark.parametrize("radius", [2.5, 5.0])
def test_a_plain_fillet_of_the_tangent_junction_falls_back_to_the_pinch_corner(radius):
    # Without the flag the kernel runs its standard algorithm first; it fails on this junction, so the kernel closes
    # it with the pinch corner: both bands taper to one point at the junction vertex, no ribbons.  The flag asks for
    # the Y transition instead: same bands far from the junction, a different corner.
    body = plate_post()
    plain = s.fillet_rsolid(body, junction_edges(body), radius, generated_faces_tag="round")
    flagged = s.fillet_rsolid(body, junction_edges(body), radius, strategy_auto_y_patch=True, generated_faces_tag="round")
    assert len(s.ql.faces().where(s.ql.tag("round")).resolve(plain)) >= 3
    assert plain.get_volume() != pytest.approx(flagged.get_volume(), rel=1e-9)
    assert plain.get_volume() == pytest.approx(flagged.get_volume(), rel=1e-3)  # differ only near the junction


@needs_y
def test_y_patch_is_recorded_and_replayed():
    with GraphSession() as session:
        body = plate_post()
        out = s.fillet_rsolid(body, junction_edges(body), 5.0, strategy_auto_y_patch=True)
        session.capture_result(value=out)
    model = s.export_model_json(session)
    assert '"strategy_auto_y_patch": true' in model.replace("'", '"') or "strategy_auto_y_patch" in str(model)
    replayed = s.replay_model_json(model)[0]
    assert replayed.get_volume() == pytest.approx(out.get_volume(), rel=1e-9)


def open_box():
    """A 20 x 20 x 10 box without its top: four walls hold the loop the patch must close."""
    box = s.make_box_rsolid(20, 20, 10)
    walls = [f for f in s.ql.faces().resolve(box) if abs(f.get_normal_at().z) < 1e-9]
    loop = []
    for wall in walls:
        top = [e for e in s.ql.edges().resolve(wall) if abs(_at(e)[2] - 10) < 1e-9]
        loop.append((top[0], wall))
    # order the loop by the angle of each edge's centre around the box axis
    loop.sort(key=lambda item: math.atan2(_at(item[0])[1], _at(item[0])[0]))
    return box, loop


def plate_with_hole():
    """A 40 x 40 x 5 plate with a 10 x 10 through hole: the top face holds the hole's loop."""
    plate = s.cut_rsolid(s.make_box_rsolid(40, 40, 5), s.make_box_rsolid(10, 10, 9, bottom_face_center=(0, 0, -2)))
    top = max(s.ql.faces().resolve(plate), key=lambda f: f.get_center().z)
    hole = [e for e in s.ql.edges().resolve(top) if max(abs(_at(e)[0]), abs(_at(e)[1])) < 6]
    hole.sort(key=lambda e: math.atan2(_at(e)[1], _at(e)[0]))
    assert len(hole) == 4
    return top, hole


@needs_graph
def test_graph_patch_meets_its_walls_in_position():
    box, loop = open_box()
    patch = s.make_surface_patch_rface([s.SurfaceBoundary(edge, "C0", wall) for edge, wall in loop], strategy_graph_patch=True)
    assert patch.get_area() == pytest.approx(400.0, rel=1e-6)


@needs_graph
@pytest.mark.parametrize("continuity", ["G1", "G2"])
def test_graph_patch_continues_its_support(continuity):
    top, hole = plate_with_hole()
    patch = s.make_surface_patch_rface([s.SurfaceBoundary(edge, continuity, top) for edge in hole], strategy_graph_patch=True)
    # tangent (and curvature) continuous with a plane: the lid is that plane, the size of the hole
    assert patch.get_area() == pytest.approx(100.0, rel=1e-6)
    assert abs(patch.get_normal_at().z) == pytest.approx(1.0, abs=1e-9)
    assert patch.get_center().z == pytest.approx(5.0, abs=1e-9)


def tube_window():
    """A tube (radius 30 outside, 26 inside, height 60) with a 40 x 24 window cut through its wall at +y, away from the
    seam: the outer cylinder face and the four edges of the window on it, ordered around the window."""
    tube = s.cut_rsolid(s.make_cylinder_rsolid(30, 60), s.make_cylinder_rsolid(26, 60))
    holed = s.cut_rsolid(tube, s.make_box_rsolid(40, 30, 24, bottom_face_center=(0, 30, 18)))
    cylinders = s.ql.faces().where(s.ql.prop("geom.type", "==", "CYLINDER")).resolve(holed)
    outer = max(cylinders, key=lambda f: f.get_area())
    window = [e for e in s.ql.edges().resolve(outer) if _at(e)[1] > 20 and 17 < _at(e)[2] < 43]
    window.sort(key=lambda e: math.atan2(_at(e)[2] - 30, _at(e)[0]))
    assert len(window) == 4
    return outer, window


def off_cylinder(face, radius=30.0):
    """How far a face is from the cylinder r = radius about z, over the nodes of a fine mesh: the largest distance and
    the largest angle (rad) between the face normal and the radial direction."""
    mesh = _cpp.mesh(face, 0.01, 0.05)
    distance = angle = 0.0
    for p, n in zip(mesh.vertices, mesh.normals):
        r = math.hypot(p[0], p[1])
        distance = max(distance, abs(r - radius))
        cos = abs(n[0] * p[0] + n[1] * p[1]) / r / math.sqrt(n[0] ** 2 + n[1] ** 2 + n[2] ** 2)
        angle = max(angle, math.acos(min(1.0, cos)))
    return distance, angle


@needs_graph
@pytest.mark.parametrize("continuity", ["C0", "G1", "G2"])
def test_graph_patch_fills_a_window_in_a_cylinder(continuity):
    outer, window = tube_window()
    patch = s.make_surface_patch_rface(
        [s.SurfaceBoundary(edge, continuity, outer) for edge in window], strategy_graph_patch=True
    )
    # the patch continues the cylinder it was cut from, to what a degree-8 graph represents (~1e-4 mm here)
    distance, angle = off_cylinder(patch)
    assert distance < 1e-3
    assert angle < 2e-3
    # the piece of the cylinder: radius x opening angle x height
    assert patch.get_area() == pytest.approx(30 * 2 * math.asin(2 / 3) * 24, rel=1e-4)


@needs_graph
def test_graph_patch_is_far_closer_to_a_cylinder_than_the_plate_filling():
    outer, window = tube_window()
    boundaries = [s.SurfaceBoundary(edge, "G1", outer) for edge in window]
    plate, _ = off_cylinder(s.make_surface_patch_rface(boundaries))  # about 0.39 mm off
    graph, _ = off_cylinder(s.make_surface_patch_rface(boundaries, strategy_graph_patch=True))
    assert graph < 1e-3 < plate
    assert graph < plate / 100


@needs_graph
def test_graph_patch_refuses_what_it_cannot_represent():
    box, loop = open_box()
    with pytest.raises(s.SimpleCADError, match="support face"):
        s.make_surface_patch_rface([s.SurfaceBoundary(edge, "G1") for edge, _ in loop], strategy_graph_patch=True)
    with pytest.raises(s.SimpleCADError, match="no holes"):
        s.make_surface_patch_rface(
            [s.SurfaceBoundary(edge, "G1", wall) for edge, wall in loop],
            strategy_graph_patch=True,
            settings=s.SurfaceFillingSettings(),
        )
